import { z } from "zod";

// Tables
export const RestaurantTableSchema = z.object({
  id: z.string().uuid(),
  business_id: z.string().uuid(),
  name_or_number: z.string().min(1, "Nombre o número requerido"),
  capacity: z.number().nullable().optional(),
  status: z.enum(["available", "occupied"]).default("available"),
  current_order_id: z.string().uuid().nullable().optional(),
  sort_order: z.number().optional().default(0),
  qr_version: z.number().optional().default(1),
  qr_is_active: z.boolean().optional().default(true),
  created_at: z.string(),
  updated_at: z.string(),
});

export type RestaurantTable = z.infer<typeof RestaurantTableSchema>;

export const CreateRestaurantTableSchema = RestaurantTableSchema.omit({
  id: true,
  business_id: true,
  current_order_id: true,
  created_at: true,
  updated_at: true,
});
export type CreateRestaurantTableDTO = z.infer<typeof CreateRestaurantTableSchema>;

export interface RestaurantTableActiveOrder {
  id: string;
  order_number: number;
  customer_name: string | null;
  total: number;
  status: string;
  payment_status: string;
  items_count: number;
  created_at: string;
  notes?: string | null;
}

export interface RestaurantTableWithOrder extends RestaurantTable {
  activeOrder?: RestaurantTableActiveOrder | null;
}

export interface RestaurantTablesSummary {
  total: number;
  available: number;
  occupied: number;
  occupancyRate: number; // Porcentaje de ocupación 0 - 100
}

export interface CreateTableInput {
  name_or_number: string;
  capacity?: number;
  sort_order?: number;
}

export interface UpdateTableInput {
  name_or_number?: string;
  capacity?: number;
  sort_order?: number;
}

// Orders
export const OrderStatusEnum = z.enum(["received", "in_preparation", "ready", "delivered", "cancelled"]);
export const OrderTypeEnum = z.enum(["dine_in", "takeout", "delivery"]);
export const ChannelOriginEnum = z.enum(["in_person", "whatsapp", "digital_menu"]);
export const PaymentStatusEnum = z.enum(["pending", "paid", "partial"]);

export const RestaurantOrderSchema = z.object({
  id: z.string().uuid(),
  business_id: z.string().uuid(),
  order_number: z.number(),
  status: OrderStatusEnum.default("received"),
  order_type: OrderTypeEnum,
  channel_origin: ChannelOriginEnum,
  subtotal: z.number().min(0),
  delivery_fee: z.number().default(0),
  total: z.number().min(0),
  notes: z.string().nullable().optional(),
  table_id: z.string().uuid().nullable().optional(),
  customer_name: z.string().nullable().optional(),
  customer_phone: z.string().nullable().optional(),
  delivery_address: z.string().nullable().optional(),
  delivery_reference: z.string().nullable().optional(),
  delivery_status: z.string().nullable().optional(),
  driver_name: z.string().nullable().optional(),
  delivery_verification_code: z.string().nullable().optional(),
  delivery_verification_attempts: z.number().default(0).optional(),
  payment_status: PaymentStatusEnum.default("pending"),
  idempotency_key: z.string().nullable().optional(),
  idempotency_hash: z.string().nullable().optional(),
  created_by: z.string().uuid().nullable().optional(),
  created_at: z.string(),
  updated_at: z.string(),
});

export type RestaurantOrder = z.infer<typeof RestaurantOrderSchema>;

export const CreateRestaurantOrderSchema = RestaurantOrderSchema.omit({
  id: true,
  business_id: true,
  order_number: true, // Generated by DB sequence normally, or handled in service
  created_at: true,
  updated_at: true,
});
export type CreateRestaurantOrderDTO = z.infer<typeof CreateRestaurantOrderSchema>;

// Order Items
export const RestaurantOrderItemSchema = z.object({
  id: z.string().uuid(),
  business_id: z.string().uuid(),
  order_id: z.string().uuid(),
  product_id: z.string().uuid().nullable().optional(),
  product_name: z.string().min(1),
  quantity: z.number().min(1),
  unit_price: z.number().min(0),
  subtotal: z.number().min(0),
  notes: z.string().nullable().optional(),
  modifiers: z.any().default([]),
  created_at: z.string(),
  updated_at: z.string(),
});

export type RestaurantOrderItem = z.infer<typeof RestaurantOrderItemSchema>;

export const CreateRestaurantOrderItemSchema = RestaurantOrderItemSchema.omit({
  id: true,
  business_id: true,
  order_id: true, // Inferred when creating the order
  created_at: true,
  updated_at: true,
});
export type CreateRestaurantOrderItemDTO = z.infer<typeof CreateRestaurantOrderItemSchema>;

