/**
 * Obtener lista de departamentos formateada para componentes Select / SearchSelect
 */
export function getDepartmentOptions() {
  return Object.keys(COLOMBIA_LOCATIONS).sort((a, b) => a.localeCompare(b, "es")).map((dep) => ({
    value: dep,
    label: dep,
  }));
}

/**
 * Obtener lista de municipios pertenecientes a un departamento dado
 */
export function getCitiesOptions(department?: string | null) {
  if (!department || !COLOMBIA_LOCATIONS[department]) {
    return [];
  }

  return COLOMBIA_LOCATIONS[department].map((city) => ({
    value: city,
    label: city,
  }));
}
